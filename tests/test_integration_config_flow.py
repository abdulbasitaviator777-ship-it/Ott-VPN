@pytest.fixture
async def auth_tokens(client):
    email = f"integration_{_uuid.uuid4().hex[:8]}@example.com"
    await client.post("/api/auth/register", json={"email": email, "password": "Str0ngP@ss1"})
    login_resp = await client.post("/api/auth/login", json={"email": email, "password": "Str0ngP@ss1"})
    return login_resp.json()["access_token"]


class TestConfigFlowIntegration:
    @pytest.fixture(autouse=True)
    async def _setup(self, client, auth_tokens):
        self.client = client
        self.client.headers["Authorization"] = f"Bearer {auth_tokens}"

    @pytest.mark.asyncio
    async def test_config_contains_server_pubkey_not_private(self):
        resp = await self.client.post("/api/vpn/config", params={"server_id": "in-mum-01"})
        assert resp.status_code == 200
        config_text = resp.json()["config"]
        assert "PublicKey = dGVzdFB1YmxjVGVzdEtleQ==" in config_text
        assert "server_privkey" not in config_text.lower()

    @pytest.mark.asyncio
    async def test_config_has_full_tunnel(self):
        resp = await self.client.post("/api/vpn/config", params={"server_id": "in-mum-01"})
        assert resp.status_code == 200
        config_text = resp.json()["config"]
        assert "0.0.0.0/0" in config_text
        assert "::/0" in config_text

    @pytest.mark.asyncio
    async def test_config_has_dns(self):
        resp = await self.client.post("/api/vpn/config", params={"server_id": "in-mum-01"})
        assert resp.status_code == 200
        config_text = resp.json()["config"]
        assert "DNS =" in config_text

    @pytest.mark.asyncio
    async def test_config_has_tunnel_addresses(self):
        resp = await self.client.post("/api/vpn/config", params={"server_id": "in-mum-01"})
        assert resp.status_code == 200
        config_text = resp.json()["config"]
        assert "10.66.0." in config_text
        assert "fd86::" in config_text

    @pytest.mark.asyncio
    async def test_config_has_persistent_keepalive(self):
        resp = await self.client.post("/api/vpn/config", params={"server_id": "in-mum-01"})
        assert resp.status_code == 200
        config_text = resp.json()["config"]
        assert "PersistentKeepalive = 25" in config_text

    @pytest.mark.asyncio
    async def test_config_has_mtu(self):
        resp = await self.client.post("/api/vpn/config", params={"server_id": "in-mum-01"})
        assert resp.status_code == 200
        config_text = resp.json()["config"]
        assert "MTU = 1280" in config_text

    @pytest.mark.asyncio
    async def test_config_parseable_by_client_parser(self):
        resp = await self.client.post("/api/vpn/config", params={"server_id": "in-mum-01"})
        assert resp.status_code == 200
        config_text = resp.json()["config"]
        config = parse_config(config_text)
        errors = validate_config(config)
        assert errors == [], f"Config validation errors: {errors}"
        assert config.peer.public_key == "dGVzdFB1YmxjVGVzdEtleQ=="
        assert config.endpoint_host is not None
        assert config.tunnel_ip4 is not None
        assert config.tunnel_ip6 is not None

    @pytest.mark.asyncio
    async def test_config_has_preshared_key(self):
        resp = await self.client.post("/api/vpn/config", params={"server_id": "in-mum-01"})
        assert resp.status_code == 200
        config_text = resp.json()["config"]
        assert "PresharedKey" in config_text
