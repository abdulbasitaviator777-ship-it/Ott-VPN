def generate_keypair() -> tuple[str, str]:
    """
    Generate a Curve25519 key pair.

    On Linux the `wg` tool is used.  When unavailable (e.g. Windows dev),
    the cryptography library's X25519 is used as a pure-Python fallback
    so the logic can be unit-tested anywhere.
    """
    try:
        import subprocess

        result = subprocess.run(
            ["wg", "genkey"], capture_output=True, text=True, check=True, timeout=5
        )
        private_key = result.stdout.strip()
        pub_result = subprocess.run(
            ["wg", "pubkey"], input=private_key, capture_output=True, text=True, check=True, timeout=5
        )
        public_key = pub_result.stdout.strip()
        return private_key, public_key
    except (FileNotFoundError, OSError):
        logger.info("wg binary not found, using cryptography fallback for key gen")
        return _generate_keypair_python()


def _generate_keypair_python() -> tuple[str, str]:
    """Generate a Curve25519 keypair using the cryptography library (X25519),
    encoded as WireGuard's base64 format."""
    from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
    from cryptography.hazmat.primitives.serialization import (
        Encoding, PrivateFormat, PublicFormat, NoEncryption,
    )

    private_obj = X25519PrivateKey.generate()
    private_bytes = private_obj.private_bytes(
        encoding=Encoding.Raw,
        format=PrivateFormat.Raw,
        encryption_algorithm=NoEncryption(),
    )
    public_bytes = private_obj.public_key().public_bytes(
        encoding=Encoding.Raw,
        format=PublicFormat.Raw,
    )
    private_key = base64.b64encode(private_bytes).decode("ascii")
    public_key = base64.b64encode(public_bytes).decode("ascii")
    return private_key, public_key


def generate_preshared_key() -> str:
    """Generate a WireGuard preshared key (base64)."""
    try:
        import subprocess

        result = subprocess.run(
            ["wg", "genpsk"], capture_output=True, text=True, check=True, timeout=5
        )
        return result.stdout.strip()
    except (FileNotFoundError, OSError):
        return base64.b64encode(secrets.token_bytes(32)).decode("ascii")


def _decode_wg_key(key: str) -> bytes:
    """Decode a base64 WireGuard key to raw bytes."""
    return base64.b64decode(key)


def _encode_wg_key(raw: bytes) -> str:
    """Encode raw bytes to a base64 WireGuard key."""
    return base64.b64encode(raw).decode("ascii")


def allocate_tunnel_ip(pool: str, used: set[str]) -> str:
    """Allocate the next available IP from a /24 IPv4 pool."""
    network = ipaddress.ip_network(pool, strict=False)
    for host in network.hosts():
        ip = str(host)
        if ip not in used:
            return ip
    raise RuntimeError(f"No free IPs in pool {pool}")


def allocate_tunnel_ip6(pool6: str, used: set[str]) -> str:
    """Allocate the next available IPv6 from a /64 pool."""
    network = ipaddress.ip_network(pool6, strict=False)
    for host in network.hosts():
        ip = str(host)
        if ip not in used:
            return ip
    raise RuntimeError(f"No free IPv6 in pool {pool6}")


def build_wireguard_config(
    *,
    client_private_key: str,
    server_public_key: str,
    server_endpoint: str,
    server_port: int,
    tunnel_ip: str,
    tunnel_ip6: Optional[str],
    preshared_key: Optional[str],
    allowed_ips: str = "0.0.0.0/0, ::/0",
    persistent_keepalive: int = 25,
    mtu: int = 1280,
    dns_servers: list[str],
    client_address_suffix: Optional[str] = None,
) -> str:
    """Build a complete WireGuard client configuration file content.

    Args:
        client_private_key: The client's private key (base64).
        server_public_key:  The *server's* public key (base64).  Never
                            includes the server's private key.
        server_endpoint:    Hostname or IPv4 of the WireGuard server.
        tunnel_ip:          Client's assigned tunnel IPv4 (e.g. 10.66.0.5/24).
        tunnel_ip6:         Client's assigned tunnel IPv6 (e.g. fd86::5/64).
        preshared_key:      Optional PSK for symmetric handshake protection.
        allowed_ips:        Routes pushed to the client (default full tunnel).
        persistent_keepalive: Seconds for NAT traversal (0 to disable).
        mtu:                Interface MTU.
        dns_servers:        DNS resolvers pushed to the client.
    """
    lines = ["# OTT VPN — WireGuard client configuration"]
    lines.append("# Auto-generated by OTT VPN backend. Do not distribute private keys.")
    lines.append("")
    lines.append("[Interface]")
    lines.append(f"PrivateKey = {client_private_key}")
    lines.append(f"Address = {tunnel_ip}{f', {tunnel_ip6}' if tunnel_ip6 else ''}")
    if preshared_key:
        lines.append(f"PresharedKey = {preshared_key}")
    lines.append(f"DNS = {', '.join(dns_servers)}")
    lines.append(f"MTU = {mtu}")
    if persistent_keepalive > 0:
        lines.append(f"PersistentKeepalive = {persistent_keepalive}")
    lines.append("")
    lines.append("[Peer]")
    lines.append(f"PublicKey = {server_public_key}")
    if preshared_key:
        lines.append(f"PresharedKey = {preshared_key}")
    lines.append(f"Endpoint = {server_endpoint}:{server_port}")
    lines.append(f"AllowedIPs = {allowed_ips}")
    if persistent_keepalive > 0:
        lines.append(f"PersistentKeepalive = {persistent_keepalive}")
    lines.append("")
    return "\n".join(lines)


def build_server_config(
    *,
    server_private_key: str,
    tunnel_net: str,
    tunnel_net6: Optional[str],
    listen_port: int,
    dns_forward: Optional[str],
    mtu: int = 1280,
) -> str:
    """Build a WireGuard server [Interface] section.

    This is the server-side config template.  The private key is only
    ever written to the server's local disk, never returned to clients.
    """
    lines = ["# OTT VPN — WireGuard server configuration"]
    lines.append("")
    lines.append("[Interface]")
    lines.append(f"PrivateKey = {server_private_key}")
    lines.append(f"Address = {tunnel_net}, {tunnel_net6}" if tunnel_net6 else f"Address = {tunnel_net}")
    lines.append(f"ListenPort = {listen_port}")
    lines.append(f"MTU = {mtu}")
    lines.append("PostUp = iptables -A FORWARD -i %i -j ACCEPT; iptables -A FORWARD -o %i -j ACCEPT; iptables -t nat -A POSTROUTING -o eth0 -j MASQUERADE; ip6tables -A FORWARD -i %i -j ACCEPT; ip6tables -t nat -A POSTROUTING -o eth0 -j MASQUERADE")
    lines.append("PostDown = iptables -D FORWARD -i %i -j ACCEPT; iptables -D FORWARD -o %i -j ACCEPT; iptables -t nat -D POSTROUTING -o eth0 -j MASQUERADE; ip6tables -D FORWARD -i %i -j ACCEPT; ip6tables -t nat -D POSTROUTING -o eth0 -j MASQUERADE")
    if dns_forward:
        lines.append(f"DNS = {dns_forward}")
    lines.append("")
    return "\n".join(lines)


def parse_wg_config_key(config_text: str, key: str) -> Optional[str]:
    """Extract a key=value from a WireGuard config section."""
    for line in config_text.splitlines():
        line = line.strip()
        if line.startswith(key):
            parts = line.split("=", 1)
            if len(parts) == 2:
                return parts[1].strip()
    return None
